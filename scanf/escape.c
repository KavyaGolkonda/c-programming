#include <stdio.h>

int main()
{
	printf("Hello\nWorld\n");     // \n=new line
	printf("Hello\bWorld\n");     //\b=back space
	printf("Hello\rWorld\n");     //\r=carriage return
	printf("Hello\fWorld\n");     //\f=form feed
	printf("Hello\tWorld\n");     //\t=horizontal tab
	printf("Hello\vWorld\n");     //\v=vertical tab
	printf("Hello\aWorld\n");     //\a=alarm
	printf("\"Hello World\"\n"); 
    return 0;
}

